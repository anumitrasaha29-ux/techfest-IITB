import React, { useEffect, useRef, useState } from 'react';
import { 
  Compass, 
  ArrowDown, 
  Layers, 
  Code, 
  Sparkles, 
  Move, 
  ChevronDown, 
  Cpu, 
  Globe2, 
  ShieldAlert, 
  Radio
} from 'lucide-react';
import { ASSETS } from '../../constants/assets';

interface Task3Props {
  onOpenCodeView?: () => void;
}

export const Task3ParallaxScroll: React.FC<Task3Props> = ({ onOpenCodeView }) => {
  const containerRef = useRef<HTMLDivElement>(null);
  const [scrollY, setScrollY] = useState(0);
  const [maxScroll, setMaxScroll] = useState(1000);
  const [mouseOffset, setMouseOffset] = useState({ x: 0, y: 0 });
  const [parallaxMultiplier, setParallaxMultiplier] = useState<number>(1.0);
  const [activeChapterIndex, setActiveChapterIndex] = useState(0);

  const chapters = [
    {
      id: 'chapter-1',
      number: '01',
      title: 'Neural Genesis',
      subtitle: 'The Awakening of Synthetic Synaptic Bridges',
      depth: '0m Elevation · Surface Laboratory',
      description: 'At the threshold between biological nerve endings and quantum superconducting filaments, the initial impulse sparks. Nanoscale electrode arrays map motor intention before muscle fibers can contract.',
      stat: '0.12ms Reaction Horizon',
      accent: 'text-amber-400 border-amber-500/30'
    },
    {
      id: 'chapter-2',
      number: '02',
      title: 'Titanium Architecture',
      subtitle: 'Forging the Unyielding Biomechanical Chassis',
      depth: '1,200m Elevation · Strata Tower',
      description: 'Human skeletal bone density is supplanted by laser-sintered titanium honeycomb lattice. Structural flex is calibrated to mirror natural human kinetic elasticity while absorbing catastrophic lateral impact forces.',
      stat: '1,890 MPa Tensile Monocoque',
      accent: 'text-cyan-400 border-cyan-500/30'
    },
    {
      id: 'chapter-3',
      number: '03',
      title: 'Microfluidic Equilibrium',
      subtitle: 'Continuous Thermal Dissipation Under Extreme Exertion',
      depth: '2,800m Elevation · Atmospheric Transit',
      description: 'Supercritical fluorocarbon fluids circulate through sub-dermal capillaries, whisking heat generated by continuous high-torque actuators toward passive ceramic radiating wings.',
      stat: '99.4% Heat Dissipation Rate',
      accent: 'text-emerald-400 border-emerald-500/30'
    },
    {
      id: 'chapter-4',
      number: '04',
      title: 'Planetary Synchronization',
      subtitle: 'The Distributed Sensor Mesh Network',
      depth: '4,500m Elevation · Orbital Tether Spire',
      description: 'Every augmented unit interfaces with the planetary telemetry cloud. Spatial maps, meteorological vectors, and ballistic trajectories stream directly into the synthetic visual cortex in real time.',
      stat: '10 Gbps Neural Uplink Bandwidth',
      accent: 'text-indigo-400 border-indigo-500/30'
    },
    {
      id: 'chapter-5',
      number: '05',
      title: 'Transcendence',
      subtitle: 'The Dissolution of Human and Machine Boundaries',
      depth: '8,000m Elevation · Exosphere Station',
      description: 'Consciousness is no longer confined to biological tissue. The mind flows seamlessly across quantum silicon nodes, transcending organic frailty into an eternal paradigm of biomechanical harmony.',
      stat: 'Continuous Equilibrium Achieved',
      accent: 'text-purple-400 border-purple-500/30'
    }
  ];

  // Track scroll position
  useEffect(() => {
    const handleScroll = () => {
      if (!containerRef.current) return;
      const current = containerRef.current.scrollTop;
      const max = containerRef.current.scrollHeight - containerRef.current.clientHeight;
      setScrollY(current);
      setMaxScroll(max > 0 ? max : 1);

      // Calculate active chapter
      const progress = current / (max || 1);
      const chapterIdx = Math.min(chapters.length - 1, Math.floor(progress * chapters.length));
      setActiveChapterIndex(chapterIdx);
    };

    const container = containerRef.current;
    if (container) {
      container.addEventListener('scroll', handleScroll, { passive: true });
    }
    return () => {
      if (container) {
        container.removeEventListener('scroll', handleScroll);
      }
    };
  }, [chapters.length]);

  // Track mouse coordinates for interactive 3D parallax tilt
  const handleMouseMove = (e: React.MouseEvent) => {
    const { clientX, clientY } = e;
    const { innerWidth, innerHeight } = window;
    const x = (clientX / innerWidth - 0.5) * 2; // -1 to 1
    const y = (clientY / innerHeight - 0.5) * 2; // -1 to 1
    setMouseOffset({ x, y });
  };

  const scrollToChapter = (index: number) => {
    if (!containerRef.current) return;
    const targetY = (maxScroll / (chapters.length - 1)) * index;
    containerRef.current.scrollTo({ top: targetY, behavior: 'smooth' });
  };

  const scrollProgress = maxScroll > 0 ? Math.min(100, Math.round((scrollY / maxScroll) * 100)) : 0;

  return (
    <div 
      className="min-h-screen bg-[#05070d] text-slate-100 flex flex-col relative overflow-hidden select-none"
      onMouseMove={handleMouseMove}
    >
      {/* Task Demonstration Header Bar */}
      <div className="bg-[#0a0d16] border-b border-slate-800/80 px-4 sm:px-8 py-2.5 flex items-center justify-between text-xs text-slate-400 z-50">
        <div className="flex items-center gap-3">
          <span className="font-semibold text-emerald-400 uppercase tracking-wider font-mono">Task 3</span>
          <span className="hidden sm:inline text-slate-600">/</span>
          <span className="text-slate-300 font-medium">Interactive Parallax Scrolling: Multi-Depth Cybernetic Odyssey</span>
        </div>
        <div className="flex items-center gap-3">
          {onOpenCodeView && (
            <button
              onClick={onOpenCodeView}
              className="flex items-center gap-1.5 px-3 py-1 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded border border-slate-700 transition-colors cursor-pointer"
            >
              <Code className="w-3.5 h-3.5 text-emerald-400" />
              <span>View Task 3 Code</span>
            </button>
          )}
        </div>
      </div>

      {/* Floating HUD: Parallax Elevation & Depth Controller */}
      <div className="fixed top-14 right-6 z-40 hidden md:flex flex-col gap-2 pointer-events-auto">
        <div className="p-3 bg-slate-950/85 backdrop-blur-md rounded-xl border border-slate-800 shadow-2xl text-xs space-y-2">
          <div className="flex items-center justify-between gap-4 font-mono">
            <span className="text-slate-400 uppercase">PARALLAX DEPTH:</span>
            <span className="text-emerald-400 font-bold tabular-nums">{scrollProgress}%</span>
          </div>

          <div className="w-48 bg-slate-800 h-1.5 rounded-full overflow-hidden">
            <div 
              className="bg-gradient-to-r from-emerald-500 to-cyan-400 h-full transition-all duration-150"
              style={{ width: `${scrollProgress}%` }}
            />
          </div>

          <div className="flex items-center justify-between text-[11px] text-slate-400 font-mono pt-1 border-t border-slate-800/80">
            <span>Elevation:</span>
            <span className="text-white">{chapters[activeChapterIndex].depth}</span>
          </div>
        </div>

        {/* Speed multiplier selector */}
        <div className="p-2 bg-slate-950/85 backdrop-blur-md rounded-xl border border-slate-800 flex items-center justify-between text-xs">
          <span className="text-slate-400 font-mono text-[11px] px-1">Ratio:</span>
          <div className="flex gap-1">
            {[0.5, 1.0, 1.8].map((speed) => (
              <button
                key={speed}
                onClick={() => setParallaxMultiplier(speed)}
                className={`px-2 py-0.5 rounded text-[11px] font-mono transition-colors cursor-pointer ${
                  parallaxMultiplier === speed
                    ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                {speed}x
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Fixed Chapter Quick-Navigation Rail on Left */}
      <div className="fixed left-6 top-1/2 -translate-y-1/2 z-40 hidden lg:flex flex-col gap-4">
        {chapters.map((ch, idx) => (
          <button
            key={ch.id}
            onClick={() => scrollToChapter(idx)}
            className="flex items-center gap-3 text-left group cursor-pointer"
          >
            <div 
              className={`w-3 h-3 rounded-full transition-all duration-300 border ${
                activeChapterIndex === idx
                  ? 'bg-emerald-400 border-emerald-300 scale-125 shadow-lg shadow-emerald-500/50'
                  : 'bg-slate-900 border-slate-700 group-hover:border-slate-500'
              }`}
            />
            <span className={`text-xs font-mono transition-all duration-300 ${
              activeChapterIndex === idx ? 'text-white font-semibold' : 'text-slate-500 group-hover:text-slate-300'
            }`}>
              {ch.number} · {ch.title}
            </span>
          </button>
        ))}
      </div>

      {/* Parallax Background Canvas / Image Layers */}
      <div className="fixed inset-0 pointer-events-none overflow-hidden z-0">
        {/* Layer 0: Deep Starfield & Nebula Gradient (Movement: slowest) */}
        <div 
          className="absolute inset-0 bg-gradient-to-b from-[#030408] via-[#070b14] to-[#04060c] opacity-90 transition-transform duration-75"
          style={{
            transform: `translate3d(${mouseOffset.x * 10}px, ${-scrollY * 0.04 * parallaxMultiplier + mouseOffset.y * 10}px, 0)`
          }}
        />

        {/* Layer 1: Futuristic Cityscape Backdrop (Movement: 0.15x) */}
        <div 
          className="absolute -top-32 left-0 right-0 h-[140%] opacity-40 transition-transform duration-75"
          style={{
            transform: `translate3d(${mouseOffset.x * 25}px, ${-scrollY * 0.15 * parallaxMultiplier + mouseOffset.y * 15}px, 0)`
          }}
        >
          <img 
            src={ASSETS.parallaxCityscape} 
            alt="Parallax Megacity Horizon" 
            className="w-full h-full object-cover filter brightness-75 contrast-125 hue-rotate-15"
            referrerPolicy="no-referrer"
          />
          <div className="absolute inset-0 bg-gradient-to-b from-[#05070d]/60 via-transparent to-[#05070d]" />
        </div>

        {/* Layer 2: Mid-ground Floating Holographic Beams & Grid Lines (Movement: 0.35x) */}
        <div 
          className="absolute inset-0 opacity-20 transition-transform duration-75"
          style={{
            backgroundImage: `radial-gradient(circle at 50% 50%, rgba(56, 189, 248, 0.15) 1px, transparent 1px)`,
            backgroundSize: '48px 48px',
            transform: `translate3d(${-mouseOffset.x * 40}px, ${-scrollY * 0.35 * parallaxMultiplier - mouseOffset.y * 25}px, 0)`
          }}
        />

        {/* Layer 3: Foreground Atmospheric Depth Struts & Mist (Movement: 0.6x) */}
        <div 
          className="absolute -bottom-20 -left-20 -right-20 h-96 bg-gradient-to-t from-[#05070d] via-[#05070d]/60 to-transparent transition-transform duration-75"
          style={{
            transform: `translate3d(${mouseOffset.x * 50}px, ${-scrollY * 0.6 * parallaxMultiplier}px, 0)`
          }}
        />
      </div>

      {/* Main Scrollable Content Container */}
      <div 
        ref={containerRef}
        className="flex-1 overflow-y-auto relative z-10 scroll-smooth"
        style={{ scrollBehavior: 'smooth' }}
      >
        {/* Parallax Hero Intro */}
        <div className="min-h-screen flex flex-col justify-center items-center text-center px-6 relative max-w-4xl mx-auto">
          <div className="space-y-4">
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded bg-emerald-950/60 border border-emerald-800/60 text-xs font-mono text-emerald-300">
              <Sparkles className="w-3.5 h-3.5" />
              <span>Multi-Layered Optical Parallax Engine</span>
            </div>

            <h1 className="text-4xl sm:text-6xl font-extrabold font-display uppercase tracking-tight text-white leading-tight">
              The Biomechanical Ascent
            </h1>

            <p className="text-slate-300 text-base sm:text-lg max-w-2xl mx-auto leading-relaxed">
              Scroll down to descend into the five phases of human-cybernetic evolution. 
              Layers shift at calibrated velocities to create authentic spatial depth.
            </p>

            <div className="pt-6 flex flex-col items-center gap-3">
              <button
                onClick={() => scrollToChapter(0)}
                className="px-6 py-3 bg-emerald-400 hover:bg-emerald-300 text-black text-xs font-bold uppercase tracking-wider rounded transition-colors flex items-center gap-2 cursor-pointer shadow-lg shadow-emerald-500/20"
              >
                <span>Initiate Scroll Sequence</span>
                <ArrowDown className="w-4 h-4 animate-bounce" />
              </button>
              <div className="text-[11px] font-mono text-slate-500">
                Move mouse to test interactive depth parallax
              </div>
            </div>
          </div>
        </div>

        {/* Narrative Chapters Sequence */}
        <div className="space-y-48 py-24 px-6 max-w-5xl mx-auto">
          {chapters.map((ch, idx) => (
            <div 
              key={ch.id} 
              className={`min-h-[70vh] flex items-center ${idx % 2 === 0 ? 'justify-start' : 'justify-end'}`}
            >
              <div 
                className="w-full max-w-xl p-8 sm:p-10 bg-slate-950/90 backdrop-blur-xl border border-slate-800 rounded-2xl shadow-2xl relative transition-all duration-500 hover:border-slate-700"
                style={{
                  transform: `translateY(${(scrollY * 0.08 * (idx % 2 === 0 ? 1 : -1))}px)`
                }}
              >
                {/* Floating Chapter Index */}
                <div className="flex items-center justify-between mb-4">
                  <span className={`text-2xl sm:text-3xl font-display font-bold ${ch.accent}`}>
                    {ch.number}
                  </span>
                  <span className="text-xs font-mono text-slate-500 bg-slate-900 px-2.5 py-1 rounded border border-slate-800">
                    {ch.depth}
                  </span>
                </div>

                <div className="text-xs font-mono text-slate-400 uppercase tracking-wider mb-1">
                  {ch.subtitle}
                </div>
                <h2 className="text-2xl sm:text-3xl font-bold font-display uppercase tracking-tight text-white mb-4">
                  {ch.title}
                </h2>
                <p className="text-slate-300 text-sm sm:text-base leading-relaxed mb-6">
                  {ch.description}
                </p>

                <div className="p-3 bg-slate-900/90 rounded-lg border border-slate-800 flex items-center justify-between text-xs">
                  <span className="text-slate-400 font-mono">Calibrated Metric:</span>
                  <span className="font-mono font-bold text-white tabular-nums">{ch.stat}</span>
                </div>
              </div>
            </div>
          ))}
        </div>

        {/* Parallax Culmination Footer */}
        <div className="py-24 text-center px-6 border-t border-slate-900 bg-slate-950/80">
          <div className="max-w-xl mx-auto space-y-4">
            <div className="text-xs font-mono text-emerald-400 uppercase">Parallax Traversal Complete</div>
            <h3 className="text-2xl font-bold font-display uppercase text-white">Full Elevation Reached</h3>
            <p className="text-xs text-slate-400">
              You have traversed from Ground Zero to the Orbital Exosphere through multi-plane parallax depth.
            </p>
            <button
              onClick={() => containerRef.current?.scrollTo({ top: 0, behavior: 'smooth' })}
              className="px-5 py-2.5 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium rounded border border-slate-700 transition-colors cursor-pointer"
            >
              Return to Surface Origin
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
